"""Generate Hisab Sathi brand assets from one geometry.

Mark = the bank building from banner.png with the Nepali rupee sign (रु) cut out (even-odd),
so it stays legible when Android tints it (notification icon, themed icons).

Writes: launcher foreground + legacy mipmaps, the three alternate app icons and their
previews, the tinted in-app logo (drawable/hisabsathi.xml), the Play Store and fastlane
icons, the About-screen image and the feature graphic.

Requires: python3, rsvg-convert (librsvg, shapes Devanagari via Pango/HarfBuzz),
ImageMagick 7 (`magick`), and the Noto Sans + Noto Sans Devanagari fonts.

Usage (from the repo root):
    python3 scripts/brand/generate_brand_assets.py /tmp/brand-out app/src/main/res .
"""
import os, re, subprocess, sys

OUT = sys.argv[1]           # scratch dir for previews/intermediate files
RES = sys.argv[2]           # app/src/main/res
ROOT = sys.argv[3]          # repo root
os.makedirs(OUT, exist_ok=True)

CREAM = "#FFFFF0"
DARK = "#1A1A1F"
CHARCOAL = "#1F1F1F"
CRIMSON = "#DC143C"   # Nepal flag crimson
LIGHT = "#E6E6E6"
SAND = "#F5EEE5"

# --- building outline, in banner.png zoom coordinates (symmetric about x=410) ---
CX = 410.0
building = [(CX, 50.0),
            (CX - 285, 200), (CX - 295, 200), (CX - 295, 250), (CX - 255, 250),
            (CX - 270, 600), (CX - 300, 600), (CX - 300, 640), (CX - 350, 640), (CX - 350, 710),
            (CX + 350, 710), (CX + 350, 640), (CX + 300, 640), (CX + 300, 600), (CX + 270, 600),
            (CX + 255, 250), (CX + 295, 250), (CX + 295, 200), (CX + 285, 200)]

# --- रु glyph as vector path, via rsvg (Pango/HarfBuzz shaping) ---
def glyph_path(text, size, weight=700):
    svg = os.path.join(OUT, "glyph_in.svg")
    open(svg, "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1000" height="1000">'
        f'<text x="500" y="600" font-family="Noto Sans Devanagari" font-weight="{weight}" '
        f'font-size="{size}" text-anchor="middle">{text}</text></svg>')
    out = os.path.join(OUT, "glyph_out.svg")
    subprocess.run(["rsvg-convert", "-f", "svg", svg, "-o", out], check=True)
    ds = re.findall(r'\sd="([^"]+)"', open(out).read())
    return " ".join(ds)

def tokens(d):
    return re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?', d)

def path_points(d):
    t = tokens(d); nums = [float(x) for x in t if x not in "MLCZ"]
    return list(zip(nums[0::2], nums[1::2]))

def transform_d(d, fn):
    out = []; t = tokens(d); i = 0
    while i < len(t):
        tok = t[i]
        if tok in "MLCZ":
            out.append(tok); i += 1
        else:
            x, y = fn(float(t[i]), float(t[i + 1])); out.append(f"{x:.2f},{y:.2f}"); i += 2
    return " ".join(out)

g = glyph_path("रु", 300)
gp = path_points(g)
gx0, gx1 = min(p[0] for p in gp), max(p[0] for p in gp)
gy0, gy1 = min(p[1] for p in gp), max(p[1] for p in gp)
# place glyph centred in the building body (body spans y 250..600), height ~230
target_h = 300.0
gs = target_h / (gy1 - gy0)
gcx, gcy = (gx0 + gx1) / 2, (gy0 + gy1) / 2
def place_glyph(x, y):
    return (CX + (x - gcx) * gs, 430 + (y - gcy) * gs)
glyph_banner = transform_d(g, place_glyph)

# --- normalise mark to a unit box: centre of bbox at origin, farthest point radius = 1 ---
bx0, bx1 = min(p[0] for p in building), max(p[0] for p in building)
by0, by1 = min(p[1] for p in building), max(p[1] for p in building)
mcx, mcy = (bx0 + bx1) / 2, (by0 + by1) / 2
rmax = max(((x - mcx) ** 2 + (y - mcy) ** 2) ** 0.5 for x, y in building)

def mark_d(viewport, radius_frac, cy_offset=0.0):
    """Even-odd path: building outline + glyph hole, fitted in a circle of radius_frac*viewport/2."""
    s = (radius_frac * viewport / 2) / rmax
    c = viewport / 2
    fn = lambda x, y: (c + (x - mcx) * s, c + cy_offset + (y - mcy) * s)
    bld = "M " + " L ".join(f"{fn(x, y)[0]:.2f},{fn(x, y)[1]:.2f}" for x, y in building) + " Z"
    return bld + " " + transform_d(glyph_banner, fn)

def android_vector(path_d, fill, viewport, dp, bg=None):
    bgp = (f'    <path android:fillColor="{argb(bg)}" android:pathData="M0,0h{viewport}v{viewport}h-{viewport}z"/>\n'
           if bg else "")
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Hisab Sathi mark: bank building with the Nepali rupee sign (रु) cut out.\n'
            f'     Generated by scripts/brand/generate_brand_assets.py; regenerate rather than hand-editing. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{dp}dp"\n    android:height="{dp}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            f'{bgp}'
            f'    <path\n        android:fillColor="{argb(fill)}"\n        android:fillType="evenOdd"\n'
            f'        android:pathData="{path_d}"/>\n</vector>\n')

def argb(hexrgb):
    return "#FF" + hexrgb.lstrip("#").upper()

def svg(path_d, fill, viewport, size, bg=None, round_bg=None, extra=""):
    bgel = ""
    if bg and round_bg == "circle":
        bgel = f'<circle cx="{viewport/2}" cy="{viewport/2}" r="{viewport/2}" fill="{bg}"/>'
    elif bg and round_bg:
        bgel = f'<rect width="{viewport}" height="{viewport}" rx="{round_bg}" fill="{bg}"/>'
    elif bg:
        bgel = f'<rect width="{viewport}" height="{viewport}" fill="{bg}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {viewport} {viewport}" '
            f'width="{size}" height="{size}">{bgel}<path d="{path_d}" fill="{fill}" fill-rule="evenodd"/>{extra}</svg>')

def render(svg_text, png):
    p = os.path.join(OUT, os.path.basename(png)[:-4] + ".svg"); open(p, "w").write(svg_text)
    subprocess.run(["rsvg-convert", p, "-o", png], check=True)

def write(rel, text):
    open(os.path.join(RES, rel), "w").write(text)

# ---------- vector drawables ----------
FG_FRAC = 0.60          # adaptive foreground: mark radius = 58% of half-canvas (inside 66/108 safe zone = 61%)
fg108 = mark_d(108, FG_FRAC)
fg192 = mark_d(192, FG_FRAC)
write("drawable/ic_launcher_foreground.xml", android_vector(fg108, CREAM, 108, 108))
# monochrome/tinted logo used in-app and as notification small icon: fill most of the canvas
write("drawable/hisabsathi.xml", android_vector(mark_d(192, 0.94), "#FFFFFF", 192, 192))
variants = {"original": (CREAM, CHARCOAL), "anarchy": (CRIMSON, SAND), "zenith": (CHARCOAL, LIGHT)}
for name, (fg, bg) in variants.items():
    write(f"drawable/ic_logo_{name}_fg.xml", android_vector(fg192, fg, 192, 108))
    # preview drawable shown in Appearance → App icon, on a box of the variant's background
    write(f"drawable/hisabsathi_{name}.xml", android_vector(mark_d(192, 0.80), fg, 192, 192))

# ---------- raster launcher mipmaps (legacy fallbacks) ----------
dens = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
for d, px in dens.items():
    base = os.path.join(OUT, f"ic_{d}")
    render(svg(mark_d(108, 0.60 * 108 / 72), CREAM, 108, px, bg=DARK, round_bg=108 * 0.18), base + ".png")
    render(svg(mark_d(108, 0.60 * 108 / 72), CREAM, 108, px, bg=DARK, round_bg="circle"), base + "_round.png")
    fgpx = int(px * 108 / 48)
    render(svg(fg108, CREAM, 108, fgpx), base + "_fg.png")
    for src, dst in [(base + ".png", "ic_launcher.webp"), (base + "_round.png", "ic_launcher_round.webp"),
                     (base + "_fg.png", "ic_launcher_foreground.webp")]:
        subprocess.run(["magick", src, "-define", "webp:lossless=true", os.path.join(RES, f"mipmap-{d}", dst)], check=True)

# ---------- store icons ----------
# Play Store icon: full-bleed square (Play applies its own mask)
render(svg(mark_d(512, 0.66), CREAM, 512, 512, bg=DARK), os.path.join(ROOT, "app/src/main/ic_launcher-playstore.png"))
# F-Droid / fastlane icon: rounded square like the old one
render(svg(mark_d(512, 0.62), CREAM, 512, 512, bg=DARK, round_bg=110),
       os.path.join(ROOT, "fastlane/metadata/android/en-US/images/icon.png"))
# About-screen developer image: the mark on the banner's black
render(svg(mark_d(512, 0.62), CREAM, 512, 512, bg=DARK, round_bg="circle"), os.path.join(OUT, "dev.png"))
subprocess.run(["magick", os.path.join(OUT, "dev.png"), "-quality", "92",
                os.path.join(RES, "drawable-nodpi/lead_developer.webp")], check=True)

# ---------- feature graphic 1024x500 ----------
mark_fg = mark_d(500, 0.58)
fg_svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 500" width="1024" height="500">'
          f'<defs><radialGradient id="g" cx="50%" cy="0%" r="90%"><stop offset="0" stop-color="#2A2A31"/>'
          f'<stop offset="1" stop-color="#0E0E11"/></radialGradient></defs>'
          f'<rect width="1024" height="500" fill="url(#g)"/>'
          f'<g transform="translate(-30,0)"><path d="{mark_fg}" fill="{CREAM}" fill-rule="evenodd"/></g>'
          f'<text x="430" y="200" font-family="Noto Sans" font-weight="800" font-size="72" fill="{CREAM}">Hisab Sathi</text>'
          f'<text x="432" y="275" font-family="Noto Sans Devanagari" font-weight="700" font-size="52" fill="{CREAM}">हिसाब साथी</text>'
          f'<text x="434" y="335" font-family="Noto Sans" font-weight="600" font-size="22" fill="#B9B9C2" letter-spacing="1">'
          f"NEPAL'S PRIVATE SMS EXPENSE TRACKER</text>"
          f'<text x="434" y="375" font-family="Noto Sans" font-weight="500" font-size="20" fill="{CRIMSON}">'
          f'eSewa · Khalti · Nabil · NMB · and more · all on your phone</text></svg>')
render(fg_svg, os.path.join(ROOT, "fastlane/metadata/android/en-US/images/featureGraphic.png"))
print("generated")
